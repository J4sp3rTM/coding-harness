const assert = require('node:assert/strict')
const { createStore } = require('./src/store')
const { VersionConflictError } = require('./src/errors')

const store = createStore({ a: 1, b: 2 })
const notices = []
const unsubscribe = store.subscribe(change => notices.push(change))
const snapshot = store.batch(0, [{ type: 'set', key: 'a', value: 3 }, { type: 'delete', key: 'b' }, { type: 'set', key: 'c', value: 4 }])
assert.deepEqual(snapshot, { a: 3, c: 4 })
assert.equal(store.version, 1)
assert.equal(notices.length, 1)
assert.deepEqual(notices[0], { version: 1, before: { a: 1, b: 2 }, after: { a: 3, c: 4 }, keys: ['a', 'b', 'c'] })
assert.equal(Object.isFrozen(notices[0]), true)

const before = store.snapshot()
assert.throws(() => store.batch(0, [{ type: 'set', key: 'x', value: 1 }]), VersionConflictError)
assert.throws(() => store.batch(1, [{ type: 'set', key: 'x', value: 1 }, { type: 'wat', key: 'y' }]), /operation/)
assert.deepEqual(store.snapshot(), before)
assert.equal(store.version, 1)
assert.equal(notices.length, 1)
unsubscribe()
store.batch(1, [{ type: 'set', key: 'z', value: 9 }])
assert.equal(notices.length, 1)
console.log('transactional-batch: PASS')
